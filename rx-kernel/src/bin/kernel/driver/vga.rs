use crate::println;

#[allow(unused)]
unsafe fn init_vga() {
    let fb_base = 0x5000_0000 as *mut u8;

    unsafe {
        // ECAM
        // NOTE: In qemu, `pci_base` is 0x3000_0000 and `dev` is 1, so `dev_base` is 0x3000_8000.
        let dev_base = 0x3000_8000 as *mut u32;

        // I want VGA
        let pci_class = dev_base.add(2).read_volatile() >> 8;
        if pci_class != 0x030000 {
            panic!("virtio-vga was not found");
        }

        println!("Init Vga begining...");

        // PCI configuration
        let io_base = {
            dev_base.add(4).write_volatile(0xFFFF_FFFF);
            let fb_size = (!dev_base.add(4).read_volatile() | 0xF) as usize + 1;
            let io_base = fb_base.add(fb_size);
            dev_base.add(6).write_volatile(0xFFFF_FFFF);
            let io_size = (!dev_base.add(6).read_volatile() | 0xF) as usize + 1;

            dev_base.add(4).write_volatile(fb_base as u32 | 8);
            dev_base.add(6).write_volatile(io_base as u32 | 8);

            let cmd = dev_base.add(1);
            cmd.write_volatile(cmd.read_volatile() | 0x0002);

            println!(
                "VGA fb_base {:#08x} size {}M io_base {:#08x} size {}",
                fb_base as usize,
                (fb_size + 0x80000) >> 20,
                io_base as usize,
                io_size,
            );

            io_base
        };

        // let text_mode = Text80x25::new();
        // let color = TextModeColor::new(Color16::Yellow, Color16::Black);
        // let screen_character = ScreenCharacter::new(b'T', color);

        // VGA.lock().set_memory_start(fb_base as usize);

        // text_mode.set_mode();
        // text_mode.clear_screen();
        // text_mode.write_character(0, 0, screen_character);

        let port0300: *mut u8 = io_base.add(0x400 - 0xC0);

        // write misc
        port0300.add(0xC2).write_volatile(VGA_CONF_80X25[0][0]);

        // write seq
        for i in 0..VGA_CONF_80X25[1].len() {
            // index
            port0300.add(0xC4).write_volatile(i as u8);
            // data
            port0300.add(0xC5).write_volatile(VGA_CONF_80X25[1][i]);
        }

        // unlock CRTC D4/D5 index/data
        port0300.add(0xD4).write_volatile(0x03);
        let val03 = port0300.add(0xD5).read_volatile() | 0x80;
        port0300.add(0xD5).write_volatile(val03);
        port0300.add(0xD4).write_volatile(0x11);
        let val11 = port0300.add(0xD5).read_volatile() & !0x80;
        port0300.add(0xD5).write_volatile(val11);

        // write CRTC
        for i in 0..VGA_CONF_80X25[2].len() {
            port0300.add(0xD4).write_volatile(i as u8);
            port0300.add(0xD5).write_volatile(VGA_CONF_80X25[2][i]);
        }

        // write GC CE/CF index/data
        for i in 0..VGA_CONF_80X25[3].len() {
            port0300.add(0xCE).write_volatile(i as u8);
            port0300.add(0xCF).write_volatile(VGA_CONF_80X25[3][i]);
        }

        // write AC C0/C0 index/write instat DA
        for i in 0..VGA_CONF_80X25[4].len() {
            port0300.add(0xDA).write_volatile(0);
            port0300.add(0xC0).write_volatile(i as u8);
            port0300.add(0xC0).write_volatile(VGA_CONF_80X25[4][i]);
        }
        port0300.add(0xDA).write_volatile(0);
        port0300.add(0xC0).write_volatile(0x20);

        port0300.add(0xC6).write_volatile(0xFF);

        // palette C8 C9
        port0300.add(0xC8).write_volatile(0);
        for &i in DEFAULT_PALETTE {
            port0300.add(0xC9).write_volatile(i);
        }

        port0300.add(0xC4).write_volatile(2);
        let seq2 = port0300.add(0xC5).read_volatile();
        port0300.add(0xC4).write_volatile(4);
        let seq4 = port0300.add(0xC5).read_volatile();
        port0300.add(0xC5).write_volatile(seq4 | 0x04);

        port0300.add(0xCE).write_volatile(4);
        let gc4 = port0300.add(0xCF).read_volatile();
        port0300.add(0xCE).write_volatile(5);
        let gc5 = port0300.add(0xCF).read_volatile();
        port0300.add(0xCF).write_volatile(gc5 & !0x10);
        port0300.add(0xCE).write_volatile(6);
        let gc6 = port0300.add(0xCF).read_volatile();
        port0300.add(0xCF).write_volatile(gc6 & !0x02);

        // B800 HERE

        //set plane 2
        let p: u8 = 2 & 3;
        let pmask: u8 = 1 << p;
        port0300.add(0xCE).write_volatile(4);
        port0300.add(0xCF).write_volatile(p);
        port0300.add(0xC4).write_volatile(2);
        port0300.add(0xC5).write_volatile(pmask);

        let mut buf = FONT_8X16;
        for i in 0..256 {
            for j in 0..16 {
                fb_base.add(i * 32 + j).write_volatile(buf[j]);
                // fb_base.add(i * 32 + j + 16).write_volatile(buf[j]);
            }
            buf = &buf[16..];
        }

        port0300.add(0xC4).write_volatile(2);
        port0300.add(0xC5).write_volatile(seq2);
        port0300.add(0xC4).write_volatile(4);
        port0300.add(0xC5).write_volatile(seq4);
        port0300.add(0xCE).write_volatile(4);
        port0300.add(0xCF).write_volatile(gc4);
        port0300.add(0xCE).write_volatile(5);
        port0300.add(0xCF).write_volatile(gc5);
        port0300.add(0xCE).write_volatile(6);
        port0300.add(0xCF).write_volatile(gc6);

        for i in 0..80 * 25 {
            fb_base.add(i * 2).write_volatile(b'h');
            fb_base.add(i * 2 + 1).write_volatile(0x7);
        }
    }
}

