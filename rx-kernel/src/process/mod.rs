unsafe fn fork_ret() {
    static mut FIRST: bool = true;

    // 父进程执行过程中透过调度器必然会持有meta锁，所以这里要强制解锁
    // 这和父进程是没有关联的
    unsafe {
        CPUManager::myproc().unwrap().meta.force_unlock();

        if FIRST {
            fs::init(ROOTDEV);
            FIRST = false;
        }
        user_trap_ret()
    };
}
